type Registry struct{ names map[string]bool }

var DefaultBuckets = []float64{0.1, 0.5, 1, 5}

func (r *Registry) Add(name string, b []float64) error {
	if r.names == nil {
		r.names = map[string]bool{}
	}
	r.names[name] = true
	return nil
}
